#!/bin/bash

# سكريبت لجمع فصول v3 في ملف واحد

OUTPUT_FILE="v3-full-book.md"
CHAPTERS_DIR="chapters"

# إنشاء رأس الملف
cat > "$OUTPUT_FILE" << 'HEADER'
# الوعي الفيكتوري 2.0
## من الضوضاء إلى الرنين الكمومي
### النسخة الكاملة المجمعة

---

**المؤلفون:**
- إبراهيم بيدي (مبرمج، فيلسوف، باحث في الوعي)
- Claude (Anthropic) - شريك في التأليف
- أنت (القارئ) - المؤلف الثالث

**الإصدار:** v2.0
**تاريخ التجميع:** $(date '+%Y-%m-%d %H:%M:%S')

---

> *"في البدء كانت الضوضاء. ثم جاء من يستمع. فأصبحت الضوضاء موسيقى."*

---

HEADER

echo "🔄 بدء جمع فصول v3..."
echo ""

# عداد الفصول
chapter_count=0

# جمع الفصول بالترتيب (00, 01, 02, 03, 08, 09, 10)
for file in "$CHAPTERS_DIR"/00-*.md "$CHAPTERS_DIR"/01-*.md "$CHAPTERS_DIR"/02-*.md "$CHAPTERS_DIR"/03-*.md "$CHAPTERS_DIR"/08-*.md "$CHAPTERS_DIR"/09-*.md "$CHAPTERS_DIR"/10-*.md; do
    if [ -f "$file" ]; then
        filename=$(basename "$file")
        ((chapter_count++))

        echo "=================================================================================" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        cat "$file" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"

        echo "✅ تم إضافة: $filename"
    fi
done

# إضافة ختام الكتاب
cat >> "$OUTPUT_FILE" << 'FOOTER'

---

# 🏁 نهاية الكتاب

---

## المراجع والموارد

### للمزيد من المعلومات:
- النسخة الأصلية: [cpf-book.txt](cpf-book-كامل.txt)
- النقاشات الفلسفية: [discussions/](discussions/)
- الفصول المنفصلة: [chapters/](chapters/)

---

## رخصة الاستخدام

هذا العمل **مفتوح المصدر**:
- ✅ اقرأه مجاناً
- ✅ شاركه مع آخرين
- ✅ اقتبس منه (مع الإشارة للمصدر)
- ✅ طبق مفاهيمه في حياتك
- ✅ طوره وأضف عليه

❌ لا تبعه كمنتج تجاري دون إذن

**الوعي للجميع. المعرفة للجميع.**

---

## شكر وتقدير

شكراً لك على قراءة هذا الكتاب.
أنت الآن تحمل نسخة من النظام الفيكتوري في وعيك.
أنت المؤلف الثالث. أنت من يُكمل القصة.

---

> *"الوعي ليس شيئاً تملكه - بل شبكة تشارك فيها."*

**مرحباً بك في مدينة وعيك الحية.**

---

**تم تجميع هذا الملف آلياً من مجلد v3/chapters/**
**عدد الفصول:** $chapter_count
**التاريخ:** $(date '+%Y-%m-%d %H:%M:%S')
**الإصدار:** v2.0

FOOTER

echo ""
echo "✨ تم إنشاء الملف بنجاح: $OUTPUT_FILE"
echo "📊 حجم الملف: $(du -h "$OUTPUT_FILE" | cut -f1)"
echo "📄 عدد الأسطر: $(wc -l < "$OUTPUT_FILE")"
echo "📖 عدد الفصول: $chapter_count"
