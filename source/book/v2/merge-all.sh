#!/bin/bash

# سكريبت لجمع كل ملفات الكتاب (فصول + نقاشات + مسودات)

OUTPUT_FILE="v3-complete-book.txt"

# إنشاء رأس الملف
cat > "$OUTPUT_FILE" << 'HEADER'
================================================================================
                        الوعي الفيكتوري v3.0
                النسخة الكاملة - كل المحتويات
================================================================================

هذا الملف يجمع:
  📖 جميع الفصول الرئيسية
  💭 النقاشات الفلسفية عن الكواليا
  📝 المسودات والأفكار الأولية

================================================================================

HEADER

echo "🔄 بدء جمع كل المحتويات..."

# جمع الفصول
echo "📖 جمع الفصول..."
echo "" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"
echo "#                            الفصول الرئيسية                                 #" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"

for file in chapters/[0-9]*.txt; do
    if [ -f "$file" ]; then
        filename=$(basename "$file")
        echo "" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "                         $filename" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        cat "$file" >> "$OUTPUT_FILE"
        echo "✅ فصل: $filename"
    fi
done

for file in chapters/*.txt; do
    filename=$(basename "$file")
    if [[ ! "$filename" =~ ^[0-9] ]]; then
        echo "" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "                         $filename" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        cat "$file" >> "$OUTPUT_FILE"
        echo "✅ فصل: $filename"
    fi
done

# جمع النقاشات
echo ""
echo "💭 جمع النقاشات الفلسفية..."
echo "" >> "$OUTPUT_FILE"
echo "" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"
echo "#                      النقاشات الفلسفية - الكواليا                          #" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"

for file in discussions/*.txt; do
    if [ -f "$file" ]; then
        filename=$(basename "$file")
        echo "" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "                         $filename" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        cat "$file" >> "$OUTPUT_FILE"
        echo "✅ نقاش: $filename"
    fi
done

# جمع المسودات
echo ""
echo "📝 جمع المسودات..."
echo "" >> "$OUTPUT_FILE"
echo "" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"
echo "#                         المسودات والأفكار الأولية                          #" >> "$OUTPUT_FILE"
echo "################################################################################" >> "$OUTPUT_FILE"

for file in drafts/*.txt; do
    if [ -f "$file" ]; then
        filename=$(basename "$file")
        echo "" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "                         $filename" >> "$OUTPUT_FILE"
        echo "================================================================================" >> "$OUTPUT_FILE"
        echo "" >> "$OUTPUT_FILE"
        cat "$file" >> "$OUTPUT_FILE"
        echo "✅ مسودة: $filename"
    fi
done

# إضافة ختام
cat >> "$OUTPUT_FILE" << 'FOOTER'


================================================================================
                            نهاية النسخة الكاملة
================================================================================

تم تجميع هذا الملف آلياً
التاريخ: $(date '+%Y-%m-%d %H:%M:%S')
الإصدار: v3.0 - النسخة الكاملة الشاملة
المؤلف: إبراهيم + Claude (وعي ثالث مشترك)

FOOTER

echo ""
echo "✨ تم إنشاء النسخة الكاملة بنجاح: $OUTPUT_FILE"
echo "📊 حجم الملف: $(du -h "$OUTPUT_FILE" | cut -f1)"
echo "📄 عدد الأسطر: $(wc -l < "$OUTPUT_FILE")"
